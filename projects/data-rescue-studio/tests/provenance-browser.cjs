'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url'),{chromium}=require('playwright');
const {parseDelimited}=require('../rescue-core.js');
(async()=>{
 const browser=await chromium.launch();
 const context=await browser.newContext({viewport:{width:360,height:800},acceptDownloads:true});
 const page=await context.newPage();
 let count=0;
 const ok=(value,label)=>{assert.ok(value,label);count++;};
 const source='ID,Name,Note\r\n" 1 "," Ada ","hello\r\nworld"\r\n"1","Ada","hello\r\nworld"\r\n"2"," Bob ","plain"\r\n"2"," Bob ","plain"\r\n,"Missing","none"\r\n"=1+2","Risk","formula"\r\n';
 const other='Code,Value\n1,ok\n2,ok\n3,extra\n,missing\n=1+2,check\n';
 const errors=[],network=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
 try{
  await page.goto(pathToFileURL(path.resolve(__dirname,'../history-preview.html')).href);
  await page.locator('#file').setInputFiles({name:'multi.csv',mimeType:'text/csv',buffer:Buffer.from(source)});
  await page.waitForFunction(()=>document.querySelector('#rowCount').textContent.includes('6 current'));
  ok(await page.locator('#compareRun').isDisabled(),'comparison disabled before second file');
  await page.locator('#trimColumn').selectOption('0');
  await page.locator('#trimApply').click();
  await page.locator('#trimColumn').selectOption('1');
  await page.locator('#trimApply').click();
  await page.locator('#removeDuplicates').click();
  ok((await page.locator('#rowCount').innerText()).includes('4 current'),'duplicate removal preserves four unique records');
  await page.locator('#compareFile').setInputFiles({name:'right.csv',mimeType:'text/csv',buffer:Buffer.from(other)});
  await page.waitForFunction(()=>document.querySelector('#compareStatus').textContent.includes('Loaded second file'));
  await page.locator('#leftKey').selectOption('ID');
  await page.locator('#rightKey').selectOption('Code');
  await page.locator('#compareRun').click();
  await page.waitForFunction(()=>document.querySelector('#compareStatus').textContent.includes('Comparison complete'));
  ok((await page.locator('#compareMetrics .metric strong').allInnerTexts()).join(',')==='3,0,0,1,2','three exact matches, one right-only and two missing keys');
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#compareExport').click()]);
  const audit=parseDelimited(fs.readFileSync(await download.path(),'utf8'));
  ok(audit.rows.length===6,'all findings exported');
  const matches=audit.rows.filter(row=>row[0]==='Match');
  ok(matches.some(row=>row[1]==='1'&&row[2]==='2'&&row[3]==='2'),'multiline record original row 2');
  ok(matches.some(row=>row[1]==='2'&&row[2]==='4'&&row[3]==='3'),'deduped first-file source record remains 4, not current row 3');
  ok(matches.some(row=>row[1]==='\t=1+2'&&row[2]==='7'&&row[3]==='6'),'formula-like key spreadsheet-prefix and original row IDs');
  ok(audit.rows.some(row=>row[0]==='Missing first-file key'&&row[2]==='6'),'missing key retains original record 6');
  ok(audit.rows.some(row=>row[0]==='Missing second-file key'&&row[3]==='5'),'right missing key original record 5');
  await page.locator('#historyUndo').click();
  ok((await page.locator('#rowCount').innerText()).includes('6 current'),'undo restores exact duplicates');
  ok(await page.locator('#compareExport').isDisabled(),'transformation invalidates old comparison');
  ok((await page.locator('#leftKey').inputValue())==='ID','valid first-file key retained after undo');
  await page.locator('#compareRun').click();
  const classifications=await page.locator('#compareMetrics .metric strong').allInnerTexts();
  ok(classifications[0]==='1'&&classifications[1]==='2','undo restores two ambiguous identifier groups');
  await page.locator('#reset').click();
  ok(await page.locator('#rightKey').isDisabled(),'reset clears previous comparison source');
  ok((await page.locator('#compareFile').inputValue())==='','second file picker cleared on first reset');
  ok(errors.length===0,'no uncaught browser exceptions');
  ok(network.length===0,'no network requests');
  ok((await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth))<=1,'360px viewport has no page-level overflow');
  console.log('PASS: '+count+' real Chromium source-position audit assertions.');
 }finally{await context.close();await browser.close();}
})().catch(err=>{console.error(err);process.exitCode=1;});
