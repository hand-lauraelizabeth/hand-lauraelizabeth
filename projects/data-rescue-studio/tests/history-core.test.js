'use strict';
const assert=require('node:assert/strict');
const {parseDelimited,exportCsv}=require('../rescue-core.js');
const {createSession,MAX_STEPS}=require('../history-core.js');
let n=0;const equal=(a,b,m)=>{assert.deepEqual(a,b,m);n++;};const okay=(v,m)=>{assert.ok(v,m);n++;};
const input=parseDelimited('ID,Name,Comment\n1, Ada , top \n2,Ada,=2+2\n2,Ada,=2+2\n3, Bob ,notes');
const snapshot=JSON.stringify(input);
const session=createSession(input);
equal(session.current().rows.length,4,'raw starts with 4 rows');
equal(session.state().cursor,0,'zero initial steps');
okay(!session.undo(),'cannot undo original');
equal(session.apply({type:'trimWhitespace',columnIndex:1}).changed,2,'trims 2 names');
equal(session.current().rows[0][1],'Ada','working copy transformed');
equal(input.rows[0][1],' Ada ','original row intact');
equal(session.apply({type:'removeExactDuplicates'}).changed,1,'remove identical rows');
equal(session.current().rows.length,3,'dedupe reduces working data');
okay(session.undo(),'undo dedupe');
equal(session.current().rows.length,4,'undo restores duplicate');
okay(session.undo(),'undo trim');
equal(session.current().rows[0][1],' Ada ','undo restores whitespace');
okay(session.redo(),'redo trim');
equal(session.current().rows[0][1],'Ada','redo reapplies trimming');
equal(session.state().canRedo,true,'dedupe step remains redoable');
equal(session.apply({type:'trimWhitespace',columnIndex:2}).changed,1,'branch with independent transformation');
equal(session.state().canRedo,false,'new branch clears redo');
equal(session.manifest().steps.length,2,'undone branch eliminated from manifest');
equal(session.apply({type:'trimWhitespace',columnIndex:0}).applied,false,'no-op does not add history step');
equal(session.state().steps,2,'no-op preserves count');
session.recordExport({outputRows:3,exportOnlyDedupe:true,spreadsheetPrecaution:true});
const manifest=session.manifest();
equal(manifest.schema,'data-rescue-operations/v1','versioned schema');
equal(manifest.source.rowCount,4,'source size in manifest');
equal(manifest.steps[0].columnIndex,1,'column index provenance');
equal(manifest.exports[0].historyRevision,2,'export tied to revision');
equal(manifest.exports[0].exportOnlyDedupe,true,'export-only dedupe recorded');
okay(!JSON.stringify(manifest).includes('=2+2'),'no raw formula cell in manifest');
okay(!JSON.stringify(manifest).includes(' Bob '),'no raw data cell in manifest');
equal(JSON.stringify(input),snapshot,'input never mutated');
okay(exportCsv(session.current(),true).includes('Ada'),'output reflects active history');
const other=createSession(parseDelimited('a\n  x \n  x '));
equal(other.apply({type:'removeExactDuplicates'}).changed,1,'exact duplicates are removed');
equal(other.apply({type:'trimWhitespace',columnIndex:0}).changed,1,'order changes result');
equal(other.current().rows.length,1,'after prior dedupe, trim leaves one');
assert.throws(()=>session.apply({type:'trimWhitespace',columnIndex:99}),/valid column/);n++;
assert.throws(()=>session.apply({type:'sanitizeUnknown'}),/supported/);n++;
assert.throws(()=>createSession({rows:[]}),/validated/);n++;
const many=createSession(parseDelimited('A\n   x   '));
for(let i=0;i<MAX_STEPS;i++){const r=many.apply({type:'trimWhitespace',columnIndex:0});if(!r.applied)break;}
okay(many.state().steps<=MAX_STEPS,'history cap enforced');
equal(session.manifest().note.includes('not a backup'),true,'manifest states provenance limitation');
console.log('PASS: '+n+' reversible history unit assertions.');
