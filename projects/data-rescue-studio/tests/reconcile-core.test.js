const assert=require('node:assert/strict');
const {parseDelimited}=require('../rescue-core.js');
const {reconcile}=require('../reconcile-core.js');
const a=parseDelimited('ID,Name\n1,Ada\n2,Ben\n2,Duplicate\n3,Cat\n,Missing');
const b=parseDelimited('Code,Amount\n1,10\n2,20\n4,40\n,0');
const x=reconcile(a,b,'ID','Code');
assert.deepEqual(x.matches,[{key:'1',leftRow:2,rightRow:2}]);
assert.deepEqual(x.ambiguous,[{key:'2',leftRows:[3,4],rightRows:[3]}]);
assert.deepEqual(x.leftOnly,[{key:'3',row:5}]);
assert.deepEqual(x.rightOnly,[{key:'4',row:4}]);
assert.deepEqual(x.missingLeft,[6]);
assert.deepEqual(x.missingRight,[5]);
assert.equal(x.matches.length+x.ambiguous.length+x.leftOnly.length,3);
assert.throws(()=>reconcile(a,b,'missing','Code'),/valid key/);
const y=reconcile(parseDelimited('key\na\na'),parseDelimited('key\na\na'),'key','key');
assert.equal(y.matches.length,0);
assert.equal(y.ambiguous.length,1);
const z=reconcile(parseDelimited('key\nA'),parseDelimited('key\na'),'key','key');
assert.equal(z.matches.length,0);
console.log('PASS: 11 reconciliation assertions.');
