'use strict';
// Synthetic-only regression for bounded Unicode reconciliation previews.
// The reference deliberately materializes small strings; the implementation
// is evaluated with Array.from disabled to catch full-array regressions.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'reconcile-ui.js'), 'utf8');
const match = source.match(/(function auditPreview\(value\) \{[\s\S]*?\n  \})\n  function visibleFindings/);
assert.ok(match, 'extract exact committed preview function');
const sandbox = vm.createContext({});
vm.runInContext('Array.from = () => { throw Error("full-array materialization forbidden"); }', sandbox);
const preview = vm.runInContext('(' + match[1] + ')', sandbox);
function reference(value) {
  const points = Array.from(String(value));
  const omitted = Math.max(0, points.length - 116);
  const shown = omitted ? [...points.slice(0, 96), ...points.slice(-20)] : points;
  const visible = shown.map(char => {
    const code = char.codePointAt(0);
    if (char === '\\') return '\\\\';
    if (char === '\n') return '\\n';
    if (char === '\r') return '\\r';
    if (char === '\t') return '\\t';
    if (code < 32 || (code >= 127 && code <= 159) ||
          (code !== 32 && /\p{White_Space}/u.test(char)) ||
          /\p{Default_Ignorable_Code_Point}/u.test(char) ||
          /\p{Mark}/u.test(char))
      return '\\u{' + code.toString(16).toUpperCase().padStart(4, '0') + '}';
    return char;
  });
  if (omitted) visible.splice(96, 0, ' … [' + omitted + ' code points omitted] … ');
  return visible.join('');
}
let checks = 0;
function equal(actual, expected, label) { assert.equal(actual, expected, label); checks++; }
const chars = ['\\','A','é','😀','\n','\r','\t','\u0000','\u007f','\u200d','\u202e','\u2066','\u0301','𝄞','Z','\u00a0','\u2028','\u2029','\u2007','\u3000'];
for (const length of [0,1,20,95,96,97,115,116,117,118,136,300]) {
  const value = Array.from({length}, (_, i) => chars[i % chars.length]).join('');
  equal(preview(value), reference(value), 'code-point boundary '+length);
}
for (let i = 0; i < 4000; i++) {
  const length = (i * 37) % 280;
  let value = '';
  for (let j = 0; j < length; j++) value += chars[(i + j * 7) % chars.length];
  equal(preview(value), reference(value), 'deterministic Unicode case '+i);
}
// Official Unicode 17.0 PropList White_Space property (2025-06-30).
// These are independent expected literals, not generated by the UI regex.
const whiteSpaceCodes = [9,10,11,12,13,32,133,160,5760,
  ...Array.from({length:11},(_,i)=>0x2000+i),0x2028,0x2029,0x202f,0x205f,0x3000];
for (const code of whiteSpaceCodes) {
  const character = String.fromCodePoint(code);
  const expected = code === 32 ? ' ' : code === 10 ? '\\n' : code === 13 ? '\\r' :
    code === 9 ? '\\t' : '\\u{' + code.toString(16).toUpperCase().padStart(4,'0') + '}';
  equal(preview('X'+character+'Y'), 'X'+expected+'Y', 'Unicode White_Space U+'+code.toString(16));
}
// Ordinary spaces remain readable, while visually similar NBSP is disclosed.
equal(preview('A B'), 'A B', 'ordinary ASCII space remains');
equal(preview('A\u00a0B'), 'A\\u{00A0}B', 'nonbreaking space is explicit');
// A literal escape sequence must not look identical to a control or invisible code point.
equal(preview('A\\nB'), 'A\\\\nB', 'literal backslash-n is visibly doubled');
equal(preview('A\nB'), 'A\\nB', 'actual line break is escaped');
assert.notEqual(preview('A\\nB'), preview('A\nB'), 'literal and actual newline distinct'); checks++;
equal(preview('A\\tB'), 'A\\\\tB', 'literal backslash-t is visibly doubled');
equal(preview('A\tB'), 'A\\tB', 'actual tab is escaped');
assert.notEqual(preview('A\\tB'), preview('A\tB'), 'literal and actual tab distinct'); checks++;
equal(preview('A\\u{00A0}B'), 'A\\\\u{00A0}B', 'literal Unicode notation visibly doubled');
equal(preview('A\u00a0B'), 'A\\u{00A0}B', 'actual NBSP visibly escaped');
assert.notEqual(preview('A\\u{00A0}B'), preview('A\u00a0B'), 'literal notation and actual NBSP distinct'); checks++;
// Show Unicode combining marks without modifying exact identifiers.
equal(preview('Café'), 'Café', 'precomposed NFC identifier remains literal');
equal(preview('Cafe\u0301'), 'Cafe\\u{0301}', 'decomposed accent made visible');
equal(preview('A\u20dd'), 'A\\u{20DD}', 'enclosing mark made visible');
equal(preview('क\u093e'), 'क\\u{093E}', 'spacing combining mark made visible');
equal(preview('Cafe\\u{0301}'), 'Cafe\\\\u{0301}', 'literal mark notation disambiguated');
assert.notEqual(preview('Café'), preview('Cafe\u0301'), 'NFC and NFD identifiers distinct'); checks++;
const long = '😀'.repeat(1_200_000) + 'END';
const result = preview(long);
assert.ok(result.length < 300, 'long preview is bounded'); checks++;
assert.ok(result.startsWith('😀'.repeat(96)), 'prefix retains code points'); checks++;
assert.ok(result.endsWith('😀'.repeat(17) + 'END'), 'suffix retains code points'); checks++;
assert.ok(result.includes('[1199887 code points omitted]'), 'exact omitted count'); checks++;
equal(long.codePointAt(0), 0x1f600, 'input unchanged');
console.log('FT-03 bounded reconciliation preview: '+checks+'/'+checks+' PASS');
