'use strict';
const assert=require('node:assert/strict');
const {parseDelimited}=require('../rescue-core.js');
const {createSession}=require('../history-core.js');
const {replay,compare}=require('../provenance-core.js');
let passed=0;
const same=(actual,expected,msg)=>{assert.deepEqual(actual,expected,msg);passed++;};
const yes=(condition,msg)=>{assert.ok(condition,msg);passed++;};
const rejects=(fn,pattern,msg)=>{assert.throws(fn,pattern,msg);passed++;};
const source=parseDelimited('ID,Name,Note\n 1 , Ada ,q\n1,Ada,q\n2,Bob,x\n2,Bob,x\n,Missing,z');
const unchanged=JSON.stringify(source);
const history=createSession(source);
same(history.apply({type:'trimWhitespace',columnIndex:0}).changed,1,'leading key trim');
same(history.apply({type:'trimWhitespace',columnIndex:1}).changed,1,'name trim');
same(history.apply({type:'removeExactDuplicates'}).changed,2,'exact duplicates after normalizing');
const manifest=history.manifest();
const current=replay(source,manifest);
same(current.rows.length,3,'retained working records');
same(current.sourceRowNumbers,[2,4,6],'source record IDs survive both transforms');
same(current.rows[0],['1','Ada','q'],'working values normalized');
same(current.rows[1],['2','Bob','x'],'second record from original record 4');
same(JSON.stringify(source),unchanged,'original parsed source unchanged');
const right=parseDelimited('Code,Val\n1,v1\n2,v2\n3,v3\n,unknown');
const r=compare(current,right,'ID','Code');
same(r.matches.map(x=>[x.key,x.leftRow,x.rightRow]),[['1',2,2],['2',4,3]],'source IDs carried into matches');
same(r.missingLeft,[6],'missing left retains source position');
same(r.missingRight,[5],'missing right retains source position');
same(r.rightOnly,[{key:'3',row:4}],'unmatched right retains source position');
same(r.leftOnly,[],'no remaining unique left-only identifiers');
same(r.ambiguous,[],'deduped keys no longer ambiguous');
yes(history.undo(),'undo possible');
const undone=replay(source,history.manifest());
same(undone.rows.length,5,'undo restores duplicate rows');
same(undone.sourceRowNumbers,[2,3,4,5,6],'undo restores original record IDs');
same(compare(undone,right,'ID','Code').ambiguous.length,2,'undone duplicate keys stay ambiguous');
yes(history.redo(),'redo possible');
same(replay(source,history.manifest()).sourceRowNumbers,[2,4,6],'redo stable');
const tamperedSource=parseDelimited('ID,Name,Note\n 1 , Ada ,q\n1,Ada,bad\n2,Bob,x\n2,Bob,x\n,Missing,z');
rejects(()=>replay(tamperedSource,manifest),/counts do not match/,'modified source fails provenance verification');
rejects(()=>replay(parseDelimited('ID\n1'),manifest),/dimensions or format/,'wrong source dimensions rejected');
rejects(()=>replay(source,{...manifest,schema:'unknown'}),/Unknown operations manifest/,'unknown schema rejected');
rejects(()=>replay(source,{...manifest,appliedRevisions:999}),/Invalid operation sequence/,'invalid cursor rejected');
rejects(()=>replay(source,{...manifest,steps:[{...manifest.steps[0],type:'unknown'},...manifest.steps.slice(1)]}),/Unsupported operation/,'unknown transformation rejected');
rejects(()=>compare({...current,sourceRowNumbers:[2,2,6]},right,'ID','Code'),/Invalid original source/,'duplicate record IDs rejected');
rejects(()=>compare({...current,sourceRowNumbers:[2,4]},right,'ID','Code'),/Invalid original source/,'truncated record ID list rejected');
const rightMapped={...right,sourceRowNumbers:[12,19,24,40]};
same(compare(current,rightMapped,'ID','Code').matches[1].rightRow,19,'right file provenance applied');
yes(!JSON.stringify(manifest).includes('Ada'),'manifest has no cell content');
console.log('PASS: '+passed+' source-row provenance and replay assertions.');
