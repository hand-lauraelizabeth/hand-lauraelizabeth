'use strict';
const assert=require('node:assert/strict');
const {decoratePinnedScores}=require('../review/score-policy-scoped-overlay.cjs');
const overlay=require('../data/sprint3/college-search-scores.v3.json');
const extras={'105330':{sat:{p25:1010,p75:1280}},'197294':{act:{p25:23,p75:null}}};
assert.equal(overlay.school_count,6243);
assert.equal(Object.keys(overlay.institutions).length,1247);
assert.ok(overlay.institutions['208822']);
const original=JSON.stringify(overlay.institutions['208822']);
const george=decoratePinnedScores(overlay,'208822',extras);
assert.equal(george.admissionsCategoryAllowed,false);
assert.equal(george.admissionsCategoryStatus,'prohibited_by_policy');
assert.equal(JSON.stringify(overlay.institutions['208822']),original);
const nau=decoratePinnedScores(overlay,'105330',extras);
assert.equal(nau.admissionsCategoryAllowed,false);
assert.equal(nau.baselineTuple,null);
assert.equal(decoratePinnedScores(overlay,'197294',extras).descriptiveEvidence.act.p75,null);
const other=Object.keys(overlay.institutions).find(id=>id!=='208822');
assert.equal(decoratePinnedScores(overlay,other,extras).admissionsCategoryAllowed,null);
assert.equal(decoratePinnedScores(overlay,other,extras).admissionsCategoryStatus,'unchanged_existing_behavior');
assert.equal(decoratePinnedScores(overlay,'12240901',extras),null);
assert.equal(decoratePinnedScores(overlay,'999999',extras),null);
assert.throws(()=>decoratePinnedScores(overlay,'208822',{'208822':{sat:1}}),/collide/);
assert.throws(()=>decoratePinnedScores({school_count:1,institutions:{}},'208822',extras),/Unexpected/);
console.log('14 scoped overlay assertions passed');
