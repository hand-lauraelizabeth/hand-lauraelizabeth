const assert=require('node:assert/strict'),C=require('./scene-v3.js');
assert.equal(C.clamp(-2,0,1),0);
assert.equal(C.clamp(4,0,1),1);
assert.equal(C.curvature(null,100),0);
assert.equal(C.curvature({lengthM:1000,points:[]},100),0);
assert.equal(C.seabed(null,{lat:0,lon:0}),null);

const M=require('./models.js');
let f=M.flightInit('trainer');
f=M.flightStep({...f,bank:18,flightPath:5},.5);
let fv=C.flightView(f);
assert.ok(Math.abs(fv.speedKnots-f.speed*1.943844)<1e-7);
assert.ok(Math.abs(fv.altitudeFeet-f.alt*3.28084)<1e-7);
assert.ok(Math.abs(fv.verticalFpm-f.speed*Math.sin(5*Math.PI/180)*196.850394)<1e-6);
assert.equal(fv.bank,18);assert.equal(fv.path,5);
assert.equal(fv.invalidLift,f.stalled);
let wind=C.flightView({...f,heading:350,trackDeg:370,groundSpeed:40,stalled:true});
assert.equal(wind.groundTrack,10);
assert.equal(wind.invalidLift,true);
assert.ok(Math.abs(wind.groundKnots-40*1.943844)<1e-9);
assert.equal(C.traveledMeters(f,f),0);
const step=M.flightStep(f,1);
assert.ok(C.traveledMeters(f,step)>20);
assert.equal(C.traveledMeters(f,{...step,time:0}),0);
assert.equal(C.traveledMeters(f,{...step,lat:0,lon:0}),0);
const route={lengthM:3000,stations:[{name:'Documented platform',distanceM:1000,structure:'Underground'},{name:'Next',distanceM:2000,structure:'Elevated'}]};
let rs={pos:993,speed:0,limit:18.0};
let target=C.railView(rs,route,{run:{phase:'at-platform'},station:{name:'Documented platform',distance:1000}});
assert.equal(target.stop.name,'Documented platform');
assert.equal(target.remaining,7);
assert.equal(target.underground,true);
assert.equal(target.knownStructure,true);
assert.equal(target.positionKm,.993);
assert.equal(target.travelKmH,0);
assert.equal(target.ceilingKmH,64.8);
assert.equal(C.railView(rs,route,{run:{phase:'finished'},station:null}).stop,null);
assert.equal(C.railView({pos:1100,speed:4,limit:22},route,null).stop.name,'Next');
const unknown=C.railView(rs,{lengthM:3000,stations:[{name:'First',distanceM:1000}]},null);
assert.equal(unknown.knownStructure,false);
assert.equal(unknown.underground,false);
const sub=M.subStep(M.subInit(),1);
const sv=C.subView({...sub,hullSpeedKnots:3.2,requestedSpeedKnots:5,verticalSpeed:.25});
assert.equal(sv.speed,3.2);assert.equal(sv.desired,5);
assert.equal(sv.verticalLabel,'DESCENDING');
assert.equal(C.subView({...sub,verticalSpeed:-.32}).verticalLabel,'ASCENDING');
assert.equal(C.subView({...sub,verticalSpeed:0}).verticalLabel,'LEVEL');
assert.ok(Math.abs(sv.pressureBar-sub.pressure/100000)<1e-9);
assert.ok(sv.depth>=0);

assert.equal(C.pointSeparation({lat:40,lon:-73},{lat:40,lon:-73}),0);
assert.ok(C.pointSeparation({lat:40,lon:-73},{lat:40.01,lon:-73})>1000);
assert.ok(C.pointSeparation({lat:40,lon:-73},{lat:40.01,lon:-73})<1300);
assert.equal(C.pointSeparation(null,{lat:40,lon:-73}),Infinity);
assert.equal(C.railView({pos:995,limit:20},route,{run:{phase:'doors-open'},station:{name:'Documented platform',distance:1000}}).underground,true);

assert.equal(C.waterlineY(0),291);
assert.ok(C.waterlineY(50)<291);
assert.equal(C.depthAtY(50,291),50);
assert.ok(C.depthAtY(50,221)<0);
assert.ok(C.waterlineY(300)<0);
assert.equal(C.depthAtY(0,291),0);
console.log('Scene state and physics alignment tests passed.');
