const assert=require('node:assert/strict');
const M=require('./models.js'),R=require('./rail-geometry.js'),O=require('./operations.js');
const length=4235.6,stop1=784.2,stop2=2210.5;
let s={...M.trainInit('metro'),length,stops:[0,stop1,stop2,length],nearestStop:stop1};
assert.equal(s.length,length);assert.equal(s.nearestStop,stop1);
s=M.trainStep({...s,throttle:80},1);
assert.ok(s.pos>0&&s.pos<stop1);
assert.equal(s.nearestStop,stop1);
const before={...s,pos:stop1+20,speed:2};
assert.equal(M.trainStep(before,0).nearestStop,stop2);
assert.equal(O.railApproach({...s,pos:stop1,speed:.3,terminalOverrun:false},M.TRAINS.metro,stop1).platformStop,true);
assert.equal(O.railApproach({...s,pos:stop1,speed:1.2},M.TRAINS.metro,stop1).platformStop,false);
const terminal={...s,pos:length-2,speed:9,throttle:0,brake:0,length};
const overrun=M.trainStep(terminal,1);
assert.equal(overrun.pos,length);assert.equal(overrun.terminalOverrun,true);
assert.equal(O.railApproach(overrun,M.TRAINS.metro,length).platformStop,false);
const route={service:'7',name:'MTA example',lengthM:length,points:[{lat:40.75,lon:-73.95},{lat:40.75,lon:-73.90}]};
const stations=R.stationRows([{stop_name:'Sample',gtfs_stop_id:'701',gtfs_latitude:40.7501,gtfs_longitude:-73.94,daytime_routes:'7'}]);
const joined=R.attach(route,stations);
assert.equal(joined.stations.length,1);
assert.equal(R.checkpoints(joined).at(-1),length);
assert.ok(joined.stations[0].distanceM>700);
console.log('Mapped route train length, station targets and terminal overrun tests passed.');
