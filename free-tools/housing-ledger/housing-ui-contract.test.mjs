import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
const here=dirname(fileURLToPath(import.meta.url));
const html=readFileSync(join(here,'index.html'),'utf8');
const app=readFileSync(join(here,'app.mjs'),'utf8');
const css=readFileSync(join(here,'styles.css'),'utf8');
let n=0;
const ck=(v,label)=>{assert.ok(v,label);n++;};
ck(existsSync(join(here,'housing-core.mjs')),'local core exists');
ck(html.includes('src="app.mjs"'),'HTML wires app module');
ck(html.includes('href="styles.css"'),'HTML wires local CSS');
ck(app.includes("from './housing-core.mjs'"),'app imports local core');
ck(html.includes('Content-Security-Policy'),'CSP declared');
ck(html.includes("connect-src 'none'"),'network connections denied');
ck(html.includes('href="#main"'),'skip link exists');
ck(html.includes('id="main"'),'main landmark target exists');
ck(html.includes('role="alert"'),'accessible error region');
ck(html.includes('role="status"'),'accessible status region');
ck(html.includes('id="source-form"')&&html.includes('id="event-form"'),'two forms');
ck(html.includes('id="download"')&&html.includes('id="clear"'),'export and clear controls');
ck(app.includes('error.focus()'),'errors receive focus');
ck(app.includes('textContent=value'),'render untrusted text as text');
ck(!/\.innerHTML\s*=|eval\s*\(/.test(app),'no HTML injection or eval');
ck(app.includes('exportHousingJSON('),'lossless JSON export used');
ck(existsSync(join(here,'housing-import.mjs')),'local import module exists');
ck(html.includes('id="import-file"')&&html.includes('id="import"'),'accessible import controls exist');
ck(html.includes('aria-describedby="import-help"'),'file input explains local replacement');
ck(app.includes("from './housing-import.mjs'"),'app imports strict JSON reader');
ck(app.includes('mutationVersion++')&&app.includes('importRequest'),'stale asynchronous imports guarded');
ck(css.length>0,'stylesheet present');
console.log(`PASS: ${n} FT-12 app integration assertions`);
