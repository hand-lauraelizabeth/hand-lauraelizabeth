import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
import {dirname,join,extname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium,firefox,webkit} from 'playwright';
const here=dirname(fileURLToPath(import.meta.url));
const engine=process.argv[2]||'chromium';
assert.ok(Object.hasOwn({chromium,firefox,webkit},engine));
const files=new Set(['index.html','styles.css','app.mjs','housing-core.mjs','housing-import.mjs']);
const mime={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.mjs':'text/javascript; charset=utf-8'};
const server=createServer((req,res)=>{
  const name=decodeURIComponent((req.url||'/').split('?')[0]).replace(/^\//,'')||'index.html';
  if(!files.has(name)){res.writeHead(404);res.end();return;}
  res.writeHead(200,{'Content-Type':mime[extname(name)],'Cache-Control':'no-store',
    'Content-Security-Policy':"default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'none'; img-src 'none'; form-action 'none'; base-uri 'none'; object-src 'none'"});
  res.end(readFileSync(join(here,name)));
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url='http://127.0.0.1:'+server.address().port+'/';
let browser,n=0;const check=async fn=>{await fn();n++;};
try{
  browser=await ({chromium,firefox,webkit})[engine].launch({headless:true});
  const page=await browser.newPage({viewport:{width:320,height:700},acceptDownloads:true});
  const errors=[],offsite=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(url))offsite.push(r.url());});
  await page.goto(url);
  await page.locator('#source-id').fill('000-Δ/１');
  await page.locator('#source-form button').click();
  await page.locator('#event-id').fill('E-001');
  await page.locator('#event-date').fill('2026-10-03');
  await page.locator('#category').selectOption('deposit');
  await page.locator('#description').fill('Synthetic\r\n=1+1');
  const enteredDescription=await page.locator('#description').inputValue();
  await page.locator('#event-form button').click();
  await check(async()=>assert.match(await page.locator('#findings-list').innerText(),/Deposit amount not provided/));
  await page.getByRole('button',{name:'Edit event E-001'}).click();
  await check(async()=>assert.equal(await page.evaluate(()=>document.activeElement.id),'edit-event-date'));
  await page.locator('#edit-event-date').fill('2026-10-02');
  await page.locator('#edit-amount').fill('0');
  await page.locator('#edit-source-links').fill('000-Δ/１');
  await page.getByRole('button',{name:'Save event correction'}).click();
  await check(async()=>assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Edit event E-001'));
  await check(async()=>assert.match(await page.locator('#status').innerText(),/updated; review flags recalculated/));
  await check(async()=>assert.match(await page.locator('#findings-list').innerText(),/No review flags/));
  const dl=page.waitForEvent('download');
  await page.locator('#download').click();
  const json=JSON.parse(readFileSync(await (await dl).path()).toString('utf8'));
  await check(async()=>assert.equal(json.events[0].eventId,'E-001'));
  await check(async()=>assert.equal(json.events[0].amountCents,0));
  await check(async()=>assert.equal(json.events[0].description,enteredDescription));
  await check(async()=>assert.deepEqual(json.events[0].sourceIds,['000-Δ/１']));
  await page.getByRole('button',{name:'Edit event E-001'}).click();
  await page.locator('#edit-source-links').fill('missing-id');
  await page.getByRole('button',{name:'Save event correction'}).click();
  await check(async()=>assert.equal(await page.evaluate(()=>document.activeElement.id),'error'));
  await check(async()=>assert.match(await page.locator('#error').innerText(),/Unknown source ID.*Existing records were kept/));
  await check(async()=>assert.match(await page.locator('#events-list').innerText(),/000-Δ\/１/));
  await page.getByRole('button',{name:'Cancel correction'}).click();
  await check(async()=>assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Edit event E-001'));
  await check(async()=>assert.equal(await page.locator('#event-editor').isHidden(),true));
  await check(async()=>assert.equal(await page.locator('img').count(),0));
  const widths=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  await check(async()=>assert.ok(widths.scroll<=widths.client+1,JSON.stringify(widths)));
  await check(async()=>assert.deepEqual(errors,[]));
  await check(async()=>assert.deepEqual(offsite,[]));
  console.log('PASS: '+n+' FT-12 event correction browser assertions ('+engine+')');
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
