import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
import {dirname, join, extname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium, firefox, webkit} from 'playwright';

const here=dirname(fileURLToPath(import.meta.url));
const name=process.argv[2]||'chromium';
const engines={chromium,firefox,webkit};
assert.ok(Object.hasOwn(engines,name));
const files=new Set(['index.html','styles.css','app.mjs','housing-core.mjs','housing-import.mjs']);
const mime={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.mjs':'text/javascript; charset=utf-8'};
const server=createServer((req,res)=>{
  const path=decodeURIComponent((req.url||'/').split('?')[0]).replace(/^\//,'')||'index.html';
  if(!files.has(path)){res.writeHead(404);res.end();return;}
  res.writeHead(200,{'Content-Type':mime[extname(path)],'Cache-Control':'no-store',
    'Content-Security-Policy':"default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'none'; img-src 'none'; form-action 'none'; base-uri 'none'; object-src 'none'"});
  res.end(readFileSync(join(here,path)));
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url='http://127.0.0.1:'+server.address().port+'/';
let browser; let count=0;
const check=async(f)=>{await f();count++;};
try{
  browser=await engines[name].launch({headless:true});
  const page=await browser.newPage({viewport:{width:320,height:700},acceptDownloads:true});
  const errors=[],offsite=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(url))offsite.push(r.url());});
  await page.goto(url);
  await page.locator('#source-id').fill('000-A/１');
  await page.locator('#source-label').fill('Synthetic <img src=x onerror=alert(1)>');
  await page.locator('#source-form button').click();
  await page.locator('#event-id').fill('000-E/é');
  await page.locator('#event-date').fill('2026-10-02');
  await page.locator('#category').selectOption('deposit');
  await page.locator('#description').fill('Synthetic CRLF\r\n=1+1');
  await page.locator('#source-links').fill('000-A/１');
  await page.locator('#event-form button').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').click();
  const download=await downloadPromise;
  const exported=readFileSync(await download.path());
  const json=JSON.parse(exported.toString('utf8'));
  await check(async()=>assert.equal(json.sources[0].sourceId,'000-A/１'));
  await check(async()=>assert.equal(json.events[0].eventId,'000-E/é'));
  await check(async()=>assert.equal(json.events[0].sourceIds[0],'000-A/１'));
  await check(async()=>assert.equal(json.events[0].description,'Synthetic CRLF\r\n=1+1'));
  await check(async()=>assert.equal(json.findings.length,1));
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#clear').click();
  await check(async()=>assert.match(await page.locator('#status').innerText(),/0 sources/));
  await page.locator('#import-file').setInputFiles({name:'housing.json',mimeType:'application/json',buffer:exported});
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#import').click();
  await check(async()=>assert.match(await page.locator('#status').innerText(),/reopened successfully/));
  await check(async()=>assert.match(await page.locator('#sources-list').innerText(),/000-A\/１/));
  await check(async()=>assert.match(await page.locator('#events-list').innerText(),/000-E\/é/));
  await check(async()=>assert.equal(await page.locator('img').count(),0));
  await check(async()=>assert.equal(await page.locator('#import-file').inputValue(),''));
  const secondDownload=page.waitForEvent('download');
  await page.locator('#download').click();
  const exact=readFileSync(await (await secondDownload).path());
  await check(async()=>assert.deepEqual(exact,exported));
  await page.locator('#source-id').fill('000-EXTRA');
  await page.locator('#source-form button').click();
  await page.locator('#import-file').setInputFiles({name:'housing.json',mimeType:'application/json',buffer:exported});
  page.once('dialog',dialog=>dialog.dismiss());
  await page.locator('#import').click();
  await check(async()=>assert.match(await page.locator('#status').innerText(),/Import canceled/));
  await check(async()=>assert.match(await page.locator('#sources-list').innerText(),/000-EXTRA/));
  await page.locator('#import-file').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{')});
  await page.locator('#import').click();
  await check(async()=>assert.equal(await page.evaluate(()=>document.activeElement.id),'error'));
  await check(async()=>assert.match(await page.locator('#error').innerText(),/valid JSON/));
  await check(async()=>assert.match(await page.locator('#sources-list').innerText(),/000-EXTRA/));
  await page.locator('#import-file').setInputFiles({name:'housing.json',mimeType:'application/json',buffer:exported});
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#import').click();
  await check(async()=>assert.doesNotMatch(await page.locator('#sources-list').innerText(),/000-EXTRA/));
  await check(async()=>assert.equal(await page.locator('#error').isHidden(),true));
  const widths=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  await check(async()=>assert.ok(widths.scroll<=widths.client+1,JSON.stringify(widths)));
  await check(async()=>assert.deepEqual(errors,[]));
  await check(async()=>assert.deepEqual(offsite,[]));
  console.log('PASS: '+count+' FT-12 JSON reopen browser assertions ('+name+')');
}finally{
  await browser?.close();
  await new Promise(resolve=>server.close(resolve));
}
