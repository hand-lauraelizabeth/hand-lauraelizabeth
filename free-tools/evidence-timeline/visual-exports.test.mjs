import assert from 'node:assert/strict';
import {normalizeExact} from './exact-core.mjs';
import {parseExactJSON} from './json-import.mjs';
import {setReviewGroup} from './edit-group.mjs';
import {updateReviewStatus} from './reclassify.mjs';
import {exportSafeEvidenceCSV} from './safe-export.mjs';
import {timelineScale,timelineSVG} from './timeline-visual.mjs';
import {ganttParts,exportGantt,excelDate,columnName} from './gantt-export.mjs';
const original=[{sourceId:'EMAIL & <tag>',date:'2026-01-12',endDate:'2026-01-16',claim:'=HYPERLINK("https://example.invalid","Not a formula")\nOriginal _x000B_ text\u000b with emoji 🧭',status:'reported',kind:'source',group:'review'},
  {sourceId:'NOTE-02',date:'2026-01-20',claim:'Single-day milestone',status:'unresolved',kind:'observation',group:''}];
const rows=normalizeExact(original);
assert.deepEqual(parseExactJSON(JSON.stringify({schema:'evidence-timeline-v1',records:rows})),rows);
assert.equal(setReviewGroup(rows,rows[0].sourceId,'new')[0].endDate,'2026-01-16');
assert.equal(updateReviewStatus(rows,rows[0].sourceId,'corroborated')[0].endDate,'2026-01-16');
assert.throws(()=>normalizeExact([{...rows[0],endDate:'2026-01-11'}]),/End date/);
assert.throws(()=>normalizeExact([{...rows[0],endDate:'2026-02-30'}]),/End date/);
assert.throws(()=>parseExactJSON(JSON.stringify({schema:'evidence-timeline-v1',records:[{...rows[0],endDate:12}]})),/Non-text/);
assert.equal(timelineScale(rows).days,9);
assert.equal(timelineScale([{...rows[0],endDate:'2026-03-01'}]).last,timelineScale([{...rows[0],date:'2026-03-01',endDate:''}]).first);
const svg=timelineSVG(rows,{scope:'Filtered entries',total:8,filters:'Search: <script> & "literal"'});
assert.match(svg,/2 of 8 entries/);
assert.match(svg,/&lt;script&gt;/);
assert.ok(!svg.includes('<script>'));
assert.ok(!svg.includes('\u000b'));
assert.match(svg,/width="\d+(?:\.\d+)?" height="16"/);
assert.match(svg,/<path d=/);
const parts=ganttParts(rows,{scope:'Filtered entries',total:8,filters:'Search: <script>'});
const gantt=parts['xl/worksheets/sheet1.xml'],entries=parts['xl/worksheets/sheet2.xml'];
assert.match(gantt,/Filtered entries · 2 of 8 entries/);
assert.match(gantt,/ISNUMBER\(\$C9\)/);
assert.match(gantt,/sqref="E9:M10"/);
assert.match(entries,/t="inlineStr"/);
assert.match(entries,/_x005F_x000B_/);
assert.match(entries,/_x000B_/);
assert.match(entries,/🧭/);
assert.ok(!entries.includes('<x:f>'), 'User evidence is always text, never an Excel formula');
assert.match(entries,/=HYPERLINK/);
assert.match(parts['xl/styles.xml'],/<x:patternFill patternType="solid"><x:fgColor rgb="FF377B5D"\s*\/><x:bgColor rgb="FF377B5D"\s*\/>/);
assert.equal(excelDate('1900-01-01'),1);
assert.equal(excelDate('1900-02-28'),59);
assert.equal(excelDate('1900-03-01'),61);
assert.equal(excelDate('2026-01-12'),46034);
assert.equal(columnName(27),'AB');
assert.throws(()=>exportGantt([]),/at least one/);
assert.throws(()=>exportGantt([{...rows[1],date:'1899-12-31'}]),/1900/);
assert.equal(timelineScale([{...rows[1],date:'0001-01-01'}]).days,1);
const workbook=exportGantt(rows);
assert.deepEqual([...workbook.slice(0,4)],[80,75,3,4]);
assert.match(exportSafeEvidenceCSV([rows[1],{...rows[1],sourceId:'RANGE',endDate:'2026-01-21'}]),/endDate/);
const bulk=Array.from({length:10000},(_,index)=>({...rows[1],sourceId:'BULK-'+index}));
assert.equal(timelineScale(bulk).rows.length,10000);
assert.match(timelineSVG(bulk,{offset:9980,limit:20}),/entries 9981–10000 of 10000/);
console.log('PASS: date ranges, legacy JSON, metadata preservation, calendar scale, SVG escaping, XLSX literal text, formulas, Excel dates, empty/filter scope and 10k preview');
