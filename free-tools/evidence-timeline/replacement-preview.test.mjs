import assert from 'node:assert/strict';
import {previewReplacement, replacementConfirmation} from './replacement-preview.mjs';
const record = (sourceId, claim = 'Synthetic') => ({sourceId, date:'2026-10-16', claim, status:'reported', kind:'source', group:''});
const before = [record('A'),record(' A '),record('café'),record('removed')];
const after = [record('A'),record(' A ','Changed'),record('cafe\u0301'),record('new')];
const result = previewReplacement(before,after);
assert.deepEqual(result,{existing:4,incoming:4,added:2,removed:2,changed:1,unchanged:1});
assert.equal(before[1].claim,'Synthetic');
assert.equal(after[1].claim,'Changed');
assert.equal(previewReplacement([],[]).unchanged,0);
assert.equal(previewReplacement([], [record('x')]).added,1);
assert.equal(previewReplacement([record('x')], []).removed,1);
assert.equal(previewReplacement([record('x')],[record('x','Different')]).changed,1);
assert.equal(previewReplacement([record('x')],[{...record('x'),status:'disputed'}]).changed,1);
assert.equal(previewReplacement([record('x')],[{...record('x'),group:'G'}]).changed,1);
assert.equal(previewReplacement([record('x')],[record('x')]).unchanged,1);
const prompt = replacementConfirmation(result);
assert.ok(prompt.includes('1 changed under the same exact source ID'));
assert.ok(prompt.includes('Cancel keeps all current records'));
assert.ok(!prompt.includes('Synthetic'));
assert.ok(!prompt.includes('café'));
assert.throws(()=>previewReplacement(null,[]));
assert.throws(()=>previewReplacement([],null));
console.log('PASS: 15 replacement preview assertions');
