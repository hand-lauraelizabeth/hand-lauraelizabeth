import assert from 'node:assert/strict';
import {normalizeExact} from './exact-core.mjs';
import {SCHEMA,MAX_BYTES,parseExactJSON,readExactJSON} from './json-import.mjs';
let count=0;
const ok=fn=>{fn();count++};
const record={sourceId:'  INV-001  ',date:'2024-02-29',claim:'  quote  ',status:'reported',kind:'source',group:'  group'};
const json=JSON.stringify({schema:SCHEMA,records:[record]});
ok(()=>assert.equal(normalizeExact([record])[0].sourceId,'  INV-001  '));
ok(()=>assert.equal(normalizeExact([record])[0].claim,'  quote  '));
ok(()=>assert.equal(normalizeExact([record])[0].group,'  group'));
ok(()=>assert.deepEqual(parseExactJSON(json),[record]));
ok(()=>assert.deepEqual(parseExactJSON('\uFEFF'+json),[record]));
ok(()=>assert.throws(()=>normalizeExact([record,record]),/duplicate/));
ok(()=>assert.equal(normalizeExact([record,{...record,sourceId:'INV-001'}]).length,2));
ok(()=>assert.throws(()=>normalizeExact([{...record,sourceId:' '}]),/source ID/));
ok(()=>assert.throws(()=>normalizeExact([{...record,date:'2025-02-29'}]),/date/));
ok(()=>assert.equal(normalizeExact([{...record,date:'0004-02-29'}])[0].date,'0004-02-29'));
ok(()=>assert.throws(()=>parseExactJSON('{bad'),/syntax/));
ok(()=>assert.throws(()=>parseExactJSON(JSON.stringify({schema:SCHEMA,records:[{...record,extra:'x'}]})),/fields/));
ok(()=>assert.throws(()=>parseExactJSON(JSON.stringify({schema:'other',records:[record]})),/schema/));
const file=(name,bytes,size=bytes.length)=>({name,size,arrayBuffer:async()=>Uint8Array.from(bytes).buffer});
const bytes=new TextEncoder().encode(json);
assert.deepEqual(await readExactJSON(file('saved.json',bytes)),[record]);count++;
await assert.rejects(readExactJSON(file('bad.json',new Uint8Array([255]))),/UTF-8/);count++;
await assert.rejects(readExactJSON(file('bad.exe',bytes)),/JSON export/);count++;
await assert.rejects(readExactJSON(file('large.json',bytes,MAX_BYTES+1)),/exceeds/);count++;
console.log('PASS '+count+' synthetic deterministic checks');
