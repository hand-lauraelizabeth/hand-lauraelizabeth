import assert from 'node:assert/strict';
import {appendExpenseCorrection,exportEvidenceWithCorrections,MAX_CORRECTIONS} from './correction-history.mjs';
import {calculateLedger,exportJSON} from './core.mjs';
let checks=0;
const eq=(actual,expected)=>{assert.deepEqual(actual,expected);checks++;};
const rejects=(fn)=>{assert.throws(fn);checks++;};
const award={awardId:'AW-001',awardName:'Fictional grant',start:'2026-01-01',end:'2026-12-31'};
const categories=[{categoryId:'001',label:'Materials',budget:'20.00',restrictionNote:''}];
const original={transactionId:'000123',sourceId:' SRC-001 ',date:'2026-02-01',categoryId:'001',amount:'5.00',percent:'100',allocationBasis:'',evidenceRef:'receipt-A',note:'=1+2'};
const corrected={...original,sourceId:' SRC-002 ',amount:'8.00',note:'Corrección – 日本語'};
const first=appendExpenseCorrection([],original,corrected);
eq(first.length,1);
eq(first[0].revision,1);
eq(first[0].transactionId,'000123');
eq(first[0].before.sourceId,' SRC-001 ');
eq(first[0].before.amount,'5.00');
eq(first[0].before.note,'=1+2');
eq(first[0].after.sourceId,' SRC-002 ');
eq(first[0].after.note,'Corrección – 日本語');
eq(original.amount,'5.00');
eq(appendExpenseCorrection(first,corrected,{...corrected}),first);
const second=appendExpenseCorrection(first,corrected,{...corrected,evidenceRef:' receipt-B '});
eq(second.length,2);
eq(second[1].revision,2);
eq(second[1].before.amount,'8.00');
eq(second[1].after.evidenceRef,' receipt-B ');
eq(first.length,1);
rejects(()=>appendExpenseCorrection(first,original,{...corrected,transactionId:'000124'}));
rejects(()=>appendExpenseCorrection(first,original,{...corrected,amount:100}));
rejects(()=>appendExpenseCorrection(first,null,corrected));
rejects(()=>appendExpenseCorrection(Array(MAX_CORRECTIONS).fill(first[0]),original,corrected));
rejects(()=>appendExpenseCorrection('not an array',original,corrected));
const current=calculateLedger(award,categories,[corrected]);
eq(current.expenses[0].totalCents,800);
const evidence=JSON.parse(exportEvidenceWithCorrections(current,second));
eq(evidence.schema,'grant-ledger-review-v1');
eq(evidence.correctionHistory.schema,'expenditure-corrections-v1');
eq(evidence.correctionHistory.entries.length,2);
eq(evidence.correctionHistory.entries[0].before.note,'=1+2');
eq(evidence.correctionHistory.entries[0].after.note,'Corrección – 日本語');
eq(evidence.expenses[0].sourceId,' SRC-002 ');
eq(JSON.parse(exportJSON(current)).correctionHistory,undefined);
rejects(()=>calculateLedger(award,categories,[{...corrected,amount:'invalid'}]));
eq(second.length,2); // failed validation must not mutate history
console.log('PASS: '+checks+' FT-06 exact correction-history assertions');
