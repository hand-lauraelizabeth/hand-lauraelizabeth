import assert from 'node:assert/strict';
import {calculateLedger,parseMoney,parsePercent,exportJSON} from './core.mjs';
const award={awardId:' A ',awardName:'Synthetic',start:'2024-02-01',end:'2024-12-31'};
const budget=[{categoryId:'staff',label:'Staff',budget:'100.00',restrictionNote:''}];
const entry={transactionId:'TX',sourceId:' SRC ',date:'2024-02-29',categoryId:'staff',amount:'10.01',percent:'33.33',allocationBasis:'time split',evidenceRef:'R1'};
const result=calculateLedger(award,budget,[entry]);
assert.equal(parseMoney('1.01'),101);
assert.equal(parsePercent('33.33'),3333);
assert.equal(result.expenses[0].assignedCents,334);
assert.equal(result.expenses[0].unassignedCents,667);
assert.equal(result.lines[0].differenceCents,9666);
assert.equal(result.expenses[0].sourceId,' SRC ');
assert.equal(JSON.parse(exportJSON(result)).award.awardId,' A ');
assert.throws(()=>parseMoney('-1'));
assert.throws(()=>parsePercent('101'));
assert.throws(()=>calculateLedger(award,budget,[entry,entry]));
assert.throws(()=>calculateLedger(award,budget,[{...entry,categoryId:'missing'}]));
assert.throws(()=>calculateLedger({...award,start:'2025-02-29'},budget,[]));
